// Собирает СДАЧА.md — готовый текст для блока «Моя работа» в кабинете конкурса.
// Пароли тестовых аккаунтов подставляются из seed/demo-accounts.json и в консоль не печатаются.
// Использование: node scripts/make-sdacha.mjs <ссылка на прототип> [ссылка на код] [ссылка на описание]

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const [site = '<ССЫЛКА НА ПРОТОТИП>', code = '<ССЫЛКА НА РЕПОЗИТОРИЙ ИЛИ АРХИВ>', doc = '<ССЫЛКА НА ОПИСАНИЕ.pdf>'] = process.argv.slice(2);
// Пароли стенда для жюри — из файла, которого нет в открытом репозитории; иначе локальные.
const prodFile = join(root, 'seed', 'demo-accounts.prod.json');
const acc = JSON.parse(readFileSync(existsSync(prodFile) ? prodFile : join(root, 'seed', 'demo-accounts.json'), 'utf8'));
const data = JSON.parse(readFileSync(join(root, 'seed', 'data.json'), 'utf8'));
const who = (login) => [...data.students, ...data.staff].find((p) => p.login === login);
const groupOf = (login) => data.groups.find((g) => g.code === who(login).group);

const text = `# Сдача работы: номинация «Вайб-кодинг», «Цифровой деканат будущего»

Ниже — готовый текст для блока «Моя работа» на странице номинации. Скопируйте его в комментарий к работе.

---

**«Дека» — цифровой деканат в кармане** (концепт, адаптирован под ДПИ НГТУ; все данные вымышленные)

Прототип: ${site}

Тестовые аккаунты (вход по логину и паролю):

| Роль | Логин | Пароль | Что показать |
|---|---|---|---|
| Студент, ${groupOf('student1').course} курс, группа ${who('student1').group} | \`student1\` | \`${acc.student1.password}\` | всё хорошо с учёбой, готовая электронная справка с кодом проверки |
| Студент, ${groupOf('student2').course} курс, группа ${who('student2').group} | \`student2\` | \`${acc.student2.password}\` | академический долг, дисциплины под риском, отказ по заявке |
| Сотрудник деканата | \`dekanat\` | \`${acc.dekanat.password}\` | очередь заявок, смена статуса, объявления, изменение расписания |

Как убедиться, что данные разделены: войдите под \`student1\`, откройте любую заявку и скопируйте адрес; выйдите, войдите под \`student2\` и вставьте адрес — кабинет ответит «Заявка не найдена».

Сценарий на 3 минуты: \`student1\` → «Заявки» → «Справка об обучении» → отправить; \`dekanat\` → открыть заявку → «Взять в работу» → «Отметить готовой»; снова \`student1\` → уведомление, в заявке код проверки → «Страница проверки».

Исходный код: ${code}

Описание процесса создания (PDF): ${doc}

Стек: Node.js 24, Express 5, SQLite, клиент без сборки. Код писали ИИ-ассистенты: Claude Code (Fable 5.2, субагенты Sonnet 5.5) и Codex (GPT). Прототип работает до 28 ноября и после.

---

## Что нужно сделать руками перед отправкой

1. Проверить, что ссылка на прототип открывается с телефона через мобильный интернет без VPN.
2. Убедиться, что ссылки на код и описание открываются в режиме инкогнито (без входа в аккаунт).
3. В кабинете конкурса: подтверждённая почта, согласие на обработку ПД, скан студенческого, галочка Регламента.
4. Вставить текст выше в комментарий и нажать «Отправить работу». До 23:59 работу можно заменить.
`;

writeFileSync(join(root, 'СДАЧА.md'), text);
console.log('СДАЧА.md обновлён' + (site.startsWith('<') ? ' (ссылки ещё не подставлены)' : ''));
